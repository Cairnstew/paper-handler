"""Discovering and describing papers in a corpus.

A corpus is a directory of paper directories; each paper directory has one
entry document (``index.qmd`` by convention) plus whatever it references —
``references.bib``, figures, data.  A loose ``*.qmd`` sitting directly in the
corpus root is also recognised, so a scratch draft does not need a directory.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from paper_handler import frontmatter
from paper_handler.config import PROJECT_FILE, Config

#: Entry document candidates, in preference order.
ENTRY_CANDIDATES = ("index.qmd", "main.qmd")

#: Written by `init` so `quarto preview` works from the corpus root too.
QUARTO_YML = """\
# Generated by `paper-handler init`.
#
# `paper-handler render` renders papers one at a time, from inside each paper
# directory.  This file gives the corpus a Quarto project root so that
# `quarto preview papers/<name>` and corpus-wide options work too.
project:
  type: default
"""


class CorpusExistsError(RuntimeError):
    """A corpus config already exists and ``force`` was not set."""


def init_corpus(
    directory: Path,
    *,
    engine: str | None = None,
    papers_dir_name: str = "papers",
    force: bool = False,
) -> dict[str, str]:
    """Create a corpus (config, Quarto project root, paper directory).

    Shared by the CLI and the MCP server so both produce exactly the same tree.
    """
    directory = Path(directory).resolve()
    config_path = directory / PROJECT_FILE
    if config_path.exists() and not force:
        raise CorpusExistsError(f"{config_path} already exists (pass --force to overwrite)")

    directory.mkdir(parents=True, exist_ok=True)
    Config(engine=engine or "typst", papers_dir=Path(papers_dir_name)).write(config_path)

    quarto_yml = directory / "_quarto.yml"
    if not quarto_yml.exists():
        quarto_yml.write_text(QUARTO_YML, encoding="utf-8")

    corpus = directory / papers_dir_name
    corpus.mkdir(parents=True, exist_ok=True)
    return {
        "directory": str(directory),
        "config": str(config_path),
        "papers_dir": str(corpus),
        "engine": engine or "typst",
    }


#: How Quarto's ``format`` metadata maps onto our engine names.
#: ``format: pdf`` is Quarto's LaTeX-backed PDF output; ``format: typst`` is Typst.
FORMAT_TO_ENGINE = {"typst": "typst", "pdf": "latex"}
ENGINE_TO_FORMAT = {"typst": "typst", "latex": "pdf", "both": "typst"}


@dataclass(frozen=True)
class Paper:
    """One paper discovered in the corpus."""

    name: str
    dir: Path
    entry: Path
    title: str
    engine: str
    status: str

    @property
    def pdf(self) -> Path:
        """Where Quarto will write the PDF for this entry document."""
        return self.entry.with_suffix(".pdf")

    @property
    def rendered(self) -> bool:
        return self.pdf.is_file()

    @property
    def front_matter(self) -> dict[str, Any]:
        return frontmatter.read(self.entry)


def engine_from_meta(meta: dict[str, Any]) -> str | None:
    """Derive the engine from front matter, or ``None`` when it says nothing."""
    explicit = meta.get("engine")
    if isinstance(explicit, str) and explicit in ENGINE_TO_FORMAT:
        return explicit

    fmt = meta.get("format")
    if isinstance(fmt, str):
        return FORMAT_TO_ENGINE.get(fmt)
    if isinstance(fmt, dict):
        for key in ("typst", "pdf"):
            if key in fmt:
                return FORMAT_TO_ENGINE[key]
    return None


def find_entry(directory: Path) -> Path | None:
    """Pick the entry document for a paper directory."""
    for candidate in ENTRY_CANDIDATES:
        path = directory / candidate
        if path.is_file():
            return path
    # Fall back to a single unambiguous .qmd; multiple candidates are a bug the
    # author should resolve rather than a coin-flip for us to make.
    siblings = sorted(directory.glob("*.qmd"))
    if len(siblings) == 1:
        return siblings[0]
    return None


def _build(directory: Path, entry: Path, name: str) -> Paper:
    try:
        meta = frontmatter.read(entry)
    except (frontmatter.FrontMatterError, OSError):
        # A broken front matter block should not make the paper invisible;
        # it will surface when the paper is rendered.
        meta = {}
    raw_title = meta.get("title")
    return Paper(
        name=name,
        dir=directory,
        entry=entry,
        title=str(raw_title) if isinstance(raw_title, str) else entry.stem,
        engine=engine_from_meta(meta) or "typst",
        status=str(meta.get("status", "draft")),
    )


def discover(papers_dir: Path) -> list[Paper]:
    """List every paper under *papers_dir*, sorted by name."""
    papers_dir = Path(papers_dir)
    if not papers_dir.is_dir():
        return []

    papers: list[Paper] = []
    for child in sorted(papers_dir.iterdir()):
        if not child.is_dir() or child.name.startswith(".") or child.name == "__pycache__":
            continue
        entry = find_entry(child)
        if entry is not None:
            papers.append(_build(child, entry, child.name))

    for child in sorted(papers_dir.glob("*.qmd")):
        papers.append(_build(papers_dir, child, child.stem))
    return papers


def locate(target: Path, papers_dir: Path) -> Paper:
    """Resolve *target* (a paper directory, an entry document, or a name) to a Paper.

    Raises ``ValueError`` when *target* is not inside *papers_dir*, which keeps
    a stray argument from rendering something the user did not mean.
    """
    target = Path(target).expanduser()
    if not target.is_absolute():
        target = (Path.cwd() / target).resolve()
    else:
        target = target.resolve()

    if target.is_file():
        directory, entry = target.parent, target
    elif target.is_dir():
        entry = find_entry(target)
        if entry is None:
            raise ValueError(f"{target}: no index.qmd or main.qmd found")
        directory = target
    else:
        raise ValueError(f"{target}: no such file or directory")

    try:
        directory.relative_to(Path(papers_dir).resolve())
    except ValueError as exc:
        raise ValueError(
            f"{directory} is not inside the corpus ({papers_dir}); "
            "pass an explicit --papers-dir if that is intentional"
        ) from exc

    name = directory.name if directory != Path(papers_dir).resolve() else entry.stem
    return _build(directory, entry, name)
